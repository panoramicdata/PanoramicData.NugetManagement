namespace PanoramicData.NugetManagement.Web.Services.DocComments;

/// <summary>
/// Recognises source the tool must never edit.
/// </summary>
public static class GeneratedCodeDetector
{
	private const int _headerLines = 30;

	private static readonly string[] _generatedSuffixes = [".g.cs", ".g.i.cs", ".generated.cs", ".designer.cs"];

	/// <summary>
	/// Why a file counts as generated, or null when it does not.
	/// </summary>
	/// <param name="relativePath">The path relative to the repository.</param>
	/// <param name="text">The file's text.</param>
	public static string? Reason(string relativePath, string text)
	{
		var segments = relativePath.Replace('\\', '/').Split('/');

		if (segments.Take(segments.Length - 1).Any(s => s.Equals("obj", StringComparison.OrdinalIgnoreCase) || s.Equals("bin", StringComparison.OrdinalIgnoreCase)))
		{
			return "generated: under a build output folder";
		}

		if (_generatedSuffixes.Any(s => relativePath.EndsWith(s, StringComparison.OrdinalIgnoreCase)))
		{
			return "generated: file name";
		}

		var header = string.Join('\n', text.Split('\n').Take(_headerLines));

		if (header.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase)
			|| header.Contains("<autogenerated", StringComparison.OrdinalIgnoreCase))
		{
			return "generated: auto-generated header";
		}

		return text.Contains("GeneratedCode(", StringComparison.Ordinal) ? "generated: GeneratedCode attribute" : null;
	}
}
