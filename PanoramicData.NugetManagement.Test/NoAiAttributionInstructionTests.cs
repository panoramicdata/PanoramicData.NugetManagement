using PanoramicData.NugetManagement.Models;
using PanoramicData.NugetManagement.Rules;
using PanoramicData.NugetManagement.Services;
using PanoramicData.NugetManagement.Web.Remediations;

namespace PanoramicData.NugetManagement.Test;

/// <summary>
/// AI-06: CLAUDE.md and AGENTS.md tell agents not to add <c>Co-Authored-By</c> trailers or other AI
/// attribution to commits and pull requests.
/// </summary>
public class NoAiAttributionInstructionTests(ITestOutputHelper output) : TestWithOutput(output), IDisposable
{
	private readonly string _root = Directory.CreateTempSubdirectory("attribution").FullName;

	public void Dispose()
	{
		Directory.Delete(_root, recursive: true);
		GC.SuppressFinalize(this);
	}

	/// <summary>
	/// The CLAUDE.md as generated by template v1.2, as it sits in the estate's repositories.
	/// </summary>
	private static string GeneratedV12Claude => Normalise(Standards.ClaudeMdContent)
		.Replace("Version: 1.3", "Version: 1.2")
		.Replace("\n- " + Standards.NoAiAttributionInstruction, string.Empty);

	/// <summary>
	/// The AGENTS.md as generated by template v1.2.
	/// </summary>
	private static string GeneratedV12Agents => Normalise(Standards.AgentsMdContent)
		.Replace("Version: 1.3", "Version: 1.2")
		.Replace("\n\n## Commits\n\n" + Standards.NoAiAttributionInstruction, string.Empty);

	[Fact]
	public void ShouldBeRegisteredForAi06()
		=> new RemediationRegistry().Get("AI-06").Should().NotBeNull();

	[Fact]
	public void TheV12Fixtures_ShouldLackTheInstruction()
	{
		// Guards the fixtures: if the template wording moves, the Replace calls above stop matching.
		GeneratedV12Claude.Should().NotContain("Co-Authored-By").And.Contain("Version: 1.2");
		GeneratedV12Agents.Should().NotContain("Co-Authored-By").And.Contain("Version: 1.2");
	}

	[Fact]
	public async Task ShouldPass_ForTheCurrentTemplates()
	{
		var result = await EvaluateAsync(Standards.ClaudeMdContent, Standards.AgentsMdContent).ConfigureAwait(true);

		result.Passed.Should().BeTrue();
	}

	[Fact]
	public async Task ShouldBeNotApplicable_WithNeitherFile()
	{
		var result = await EvaluateAsync(null, null).ConfigureAwait(true);

		result.IsApplicable.Should().BeFalse();
	}

	[Fact]
	public async Task ShouldFail_ForTheGeneratedV12Files()
	{
		var result = await EvaluateAsync(GeneratedV12Claude, GeneratedV12Agents).ConfigureAwait(true);

		result.Passed.Should().BeFalse();
		result.Advisory!.Data["remediation_type"].Should().Be("replace_regex_in_files");
		result.Advisory.Data["globs"].Should().BeEquivalentTo(new[] { "CLAUDE.md", "AGENTS.md" });
		new RemediationRegistry().CanRemediate(result).Should().BeTrue();
	}

	[Fact]
	public async Task ShouldFail_WhenAFileAsksForTheTrailer()
	{
		// A file that mentions the trailer only to ask for it must not pass.
		var asking = GeneratedV12Claude + "\n\nEnd every commit with `Co-Authored-By: Claude <noreply@anthropic.com>`.\n";

		var result = await EvaluateAsync(asking, Standards.AgentsMdContent).ConfigureAwait(true);

		result.Passed.Should().BeFalse();
	}

	[Fact]
	public async Task Fix_ShouldTurnTheGeneratedV12FilesIntoTheCurrentTemplates()
	{
		// Fixing the estate's files must land exactly on what a new repository gets, or the fix and the
		// template drift apart.
		var (claude, agents) = await ApplyFixAsync(GeneratedV12Claude, GeneratedV12Agents).ConfigureAwait(true);

		Normalise(claude).Should().Be(Normalise(Standards.ClaudeMdContent));
		Normalise(agents).Should().Be(Normalise(Standards.AgentsMdContent));
	}

	[Fact]
	public async Task Fix_ShouldKeepCrlfLineEndings()
	{
		var (claude, agents) = await ApplyFixAsync(
			GeneratedV12Claude.Replace("\r\n", "\n").Replace("\n", "\r\n"),
			GeneratedV12Agents.Replace("\r\n", "\n").Replace("\n", "\r\n")).ConfigureAwait(true);

		claude.Replace("\r\n", string.Empty).Should().NotContain("\n");
		agents.Replace("\r\n", string.Empty).Should().NotContain("\n");
	}

	[Fact]
	public async Task Fix_ShouldPassTheRuleAfterwards()
	{
		var (claude, agents) = await ApplyFixAsync(GeneratedV12Claude, GeneratedV12Agents).ConfigureAwait(true);

		var after = await EvaluateAsync(claude, agents).ConfigureAwait(true);
		after.Passed.Should().BeTrue();
	}

	[Fact]
	public async Task ShouldOfferNoFix_ForAHandWrittenFileWithoutTheTemplateAnchor()
	{
		// A file the fix cannot place the line in still fails, but draws no wrench that changes nothing.
		const string handWritten = "# CLAUDE.md\n\nBe careful.\n";

		var result = await EvaluateAsync(handWritten, null).ConfigureAwait(true);

		result.Passed.Should().BeFalse();
		new RemediationRegistry().CanRemediate(result).Should().BeFalse();
	}

	private async Task<(string Claude, string Agents)> ApplyFixAsync(string claude, string agents)
	{
		var failing = await EvaluateAsync(claude, agents).ConfigureAwait(true);
		failing.Passed.Should().BeFalse();

		var claudePath = Path.Combine(_root, "CLAUDE.md");
		var agentsPath = Path.Combine(_root, "AGENTS.md");
		File.WriteAllText(claudePath, claude);
		File.WriteAllText(agentsPath, agents);

		var applied = new List<string>();
		new RemediationRegistry().Get("AI-06")!.Apply(_root, failing, applied, null);

		applied.Should().HaveCount(2);
		return (File.ReadAllText(claudePath), File.ReadAllText(agentsPath));
	}

	private static string Normalise(string text) => text.Replace("\r\n", "\n").Trim();

	private static async Task<RuleResult> EvaluateAsync(string? claude, string? agents)
	{
		var files = new Dictionary<string, string>();
		if (claude is not null)
		{
			files["CLAUDE.md"] = claude;
		}

		if (agents is not null)
		{
			files["AGENTS.md"] = agents;
		}

		var context = new RepositoryContext
		{
			FullName = "panoramicdata/TeamViewer.Api",
			Name = "TeamViewer.Api",
			DefaultBranch = "main",
			Options = new RepoOptions(),
			FilePaths = [.. files.Keys],
			FileContents = files
		};

		return await RuleRegistry.Rules.Single(r => r.RuleId == "AI-06")
			.EvaluateAsync(context, CancellationToken.None)
			.ConfigureAwait(false);
	}
}
