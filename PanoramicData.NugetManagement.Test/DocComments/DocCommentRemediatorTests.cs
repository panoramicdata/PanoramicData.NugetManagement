using System.Text;
using PanoramicData.NugetManagement.Web.Services;
using PanoramicData.NugetManagement.Web.Services.DocComments;

namespace PanoramicData.NugetManagement.Test.DocComments;

/// <summary>Tests for <see cref="DocCommentRemediator"/>, always against a scripted model and a temporary folder.</summary>
public sealed class DocCommentRemediatorTests : IDisposable
{
	private const string Source = "namespace N\r\n{\r\n\tpublic class Customer\r\n\t{\r\n\t\tpublic string Name { get; set; }\r\n\t}\r\n}\r\n";

	private const string GoodReply =
		"@@@ 1\n/// <summary>\n/// A customer billed by the organisation.\n/// </summary>\n@@@ 2\n/// <summary>\n/// The name shown on invoices.\n/// </summary>\n";

	private readonly string _root = Path.Combine(Path.GetTempPath(), "doccomments-" + Guid.NewGuid().ToString("N"));

	public DocCommentRemediatorTests() => Directory.CreateDirectory(_root);

	public void Dispose()
	{
		Directory.Delete(_root, recursive: true);
		GC.SuppressFinalize(this);
	}

	private sealed class ScriptedModel(Func<string, string> reply) : IDocCommentModel
	{
		public List<string> Prompts { get; } = [];

		public List<string> Systems { get; } = [];

		public Task<string> AskAsync(string systemPrompt, string userPrompt, CancellationToken cancellationToken)
		{
			Systems.Add(systemPrompt);
			Prompts.Add(userPrompt);

			return Task.FromResult(reply(userPrompt));
		}
	}

	private sealed class ThrowingModel : IDocCommentModel
	{
		public Task<string> AskAsync(string systemPrompt, string userPrompt, CancellationToken cancellationToken)
			=> throw new HttpRequestException("connection refused");
	}

	private string Write(string relative, string text, bool bom = false)
	{
		var path = Path.Combine(_root, relative);
		Directory.CreateDirectory(Path.GetDirectoryName(path)!);
		File.WriteAllText(path, text, new UTF8Encoding(bom));

		return path;
	}

	private static MissingDocDiagnostic[] Both(string path) => [new(path, 3, 1, "N.Customer"), new(path, 5, 1, "N.Customer.Name")];

	[Fact]
	public async Task WritesValidatedDocsAndKeepsBomAndCrlf()
	{
		var path = Write("Customer.cs", Source, bom: true);
		var remediator = new DocCommentRemediator(new ScriptedModel(_ => GoodReply));

		var results = await remediator.RunAsync(_root, Both(path), dryRun: false, TestContext.Current.CancellationToken).ConfigureAwait(true);

		results.Should().ContainSingle().Which.Inserted.Should().Be(2);
		var bytes = await File.ReadAllBytesAsync(path, TestContext.Current.CancellationToken).ConfigureAwait(true);
		bytes.Take(3).Should().Equal(0xEF, 0xBB, 0xBF);
		var text = Encoding.UTF8.GetString(bytes, 3, bytes.Length - 3);
		text.Should().Contain("\t/// A customer billed by the organisation.\r\n").And.Contain("\t\t/// The name shown on invoices.\r\n");
		text.Replace("\r\n", string.Empty).Should().NotContain("\n");
	}

	[Fact]
	public async Task DryRunWritesNothing()
	{
		var path = Write("Customer.cs", Source);
		var remediator = new DocCommentRemediator(new ScriptedModel(_ => GoodReply));

		var results = await remediator.RunAsync(_root, Both(path), dryRun: true, TestContext.Current.CancellationToken).ConfigureAwait(true);

		results.Single().Inserted.Should().Be(2);
		results.Single().Written.Should().BeFalse();
		File.ReadAllText(path).Should().Be(Source);
	}

	[Fact]
	public async Task ACosmeticAnswerIsRejectedAndTheMemberStaysUndocumented()
	{
		var path = Write("Customer.cs", Source);
		var model = new ScriptedModel(_ => "@@@ 1\n/// <summary>\n/// A customer billed by the organisation.\n/// </summary>\n@@@ 2\n/// <summary>\n/// Gets or sets the Name.\n/// </summary>\n");
		var remediator = new DocCommentRemediator(model);

		var result = (await remediator.RunAsync(_root, Both(path), dryRun: false, TestContext.Current.CancellationToken).ConfigureAwait(true)).Single();

		result.Inserted.Should().Be(1);
		result.Rejected.Should().ContainSingle().Which.Should().Contain("restates");
		File.ReadAllText(path).Should().NotContain("Gets or sets");
		model.Prompts.Should().HaveCount(2, "the rejected slot gets exactly one targeted retry");
	}

	[Fact]
	public async Task TheRetryAsksOnlyForTheBadSlots()
	{
		var path = Write("Customer.cs", Source);
		var model = new ScriptedModel(prompt => prompt.Contains("Undocumented slots (1)", StringComparison.Ordinal)
			? "@@@ 2\n/// <summary>\n/// The name shown on invoices.\n/// </summary>\n"
			: "@@@ 1\n/// <summary>\n/// A customer billed by the organisation.\n/// </summary>\n");
		var remediator = new DocCommentRemediator(model);

		var result = (await remediator.RunAsync(_root, Both(path), dryRun: true, TestContext.Current.CancellationToken).ConfigureAwait(true)).Single();

		result.Inserted.Should().Be(2);
		model.Prompts.Should().HaveCount(2);
	}

	[Fact]
	public async Task NeverTouchesGeneratedCode()
	{
		var designer = Write("Customer.Designer.cs", Source);
		var header = Write("Header.cs", "// <auto-generated>\r\n// stuff\r\n// </auto-generated>\r\n" + Source);
		var attributed = Write("Attr.cs", "[System.CodeDom.Compiler.GeneratedCode(\"x\", \"1\")]\r\n" + Source);
		var inObj = Write(Path.Combine("obj", "Debug", "Thing.cs"), Source);
		var model = new ScriptedModel(_ => GoodReply);
		var remediator = new DocCommentRemediator(model);

		var results = await remediator.RunAsync(
			_root,
			[.. new[] { designer, header, attributed, inObj }.SelectMany(Both)],
			dryRun: false,
			TestContext.Current.CancellationToken).ConfigureAwait(true);

		results.Should().HaveCount(4).And.OnlyContain(r => r.Skipped != null && r.Skipped.Contains("generated"));
		model.Prompts.Should().BeEmpty("generated code must not even be sent to the model");
		model.Systems.Should().BeEmpty();
	}

	[Fact]
	public async Task RefusesAPathOutsideTheRepository()
	{
		var outside = Path.Combine(Path.GetTempPath(), "outside-" + Guid.NewGuid().ToString("N") + ".cs");
		await File.WriteAllTextAsync(outside, Source, TestContext.Current.CancellationToken).ConfigureAwait(true);

		try
		{
			var model = new ScriptedModel(_ => GoodReply);
			var results = await new DocCommentRemediator(model)
				.RunAsync(_root, Both(outside), dryRun: false, TestContext.Current.CancellationToken).ConfigureAwait(true);

			results.Single().Skipped.Should().Contain("outside");
			File.ReadAllText(outside).Should().Be(Source);
			model.Prompts.Should().BeEmpty();
		}
		finally
		{
			File.Delete(outside);
		}
	}

	[Fact]
	public async Task AModelFailureSkipsTheFileAndLeavesItIntact()
	{
		var path = Write("Customer.cs", Source);
		var remediator = new DocCommentRemediator(new ThrowingModel());

		var result = (await remediator.RunAsync(_root, Both(path), dryRun: false, TestContext.Current.CancellationToken).ConfigureAwait(true)).Single();

		result.Skipped.Should().Contain("model");
		File.ReadAllText(path).Should().Be(Source);
	}

	[Fact]
	public async Task AFileThatIsNotUtf8IsSkipped()
	{
		var path = Path.Combine(_root, "Latin.cs");
		byte[] bytes = [.. "// caf"u8, 0xE9, .. "\r\nclass A { }\r\n"u8];
		await File.WriteAllBytesAsync(path, bytes, TestContext.Current.CancellationToken).ConfigureAwait(true);

		var results = await new DocCommentRemediator(new ScriptedModel(_ => GoodReply))
			.RunAsync(_root, [new(path, 2, 1, "A")], dryRun: false, TestContext.Current.CancellationToken).ConfigureAwait(true);

		results.Single().Skipped.Should().Contain("UTF-8");
	}

	[Fact]
	public async Task TheChatModelAdapterSendsNoToolsAndReturnsTheText()
	{
		var chat = new RecordingChat("@@@ 1\n/// <summary>Hi.</summary>");
		var adapter = new ChatDocCommentModel(chat);

		var reply = await adapter.AskAsync("sys", "usr", TestContext.Current.CancellationToken).ConfigureAwait(true);

		reply.Should().Contain("@@@ 1");
		chat.ToolCount.Should().Be(0, "the model proposes text only; it is never given a way to act");
		chat.System.Should().Be("sys");
		chat.Roles.Should().Equal("user");
		chat.Streamed.Should().BeFalse();
		chat.Cancellable.Should().BeTrue("the caller's token is passed through");
	}

	private sealed class RecordingChat(string text) : IChatModel
	{
		public int ToolCount { get; private set; } = -1;

		public string? System { get; private set; }

		public string[] Roles { get; private set; } = [];

		public bool Streamed { get; private set; } = true;

		public bool Cancellable { get; private set; }

		public Task<AiModelTurn> NextAsync(
			string systemPrompt,
			IReadOnlyList<AiMessage> conversation,
			IReadOnlyList<AiToolSpec> tools,
			Action<AiStreamDelta>? onDelta,
			CancellationToken cancellationToken)
		{
			ToolCount = tools.Count;
			System = systemPrompt;
			Roles = [.. conversation.Select(m => m.Role)];
			Streamed = onDelta is not null;
			Cancellable = cancellationToken.CanBeCanceled;

			return Task.FromResult(new AiModelTurn(text, []));
		}
	}
}
