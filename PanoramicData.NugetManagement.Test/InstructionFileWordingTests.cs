using PanoramicData.NugetManagement.Models;
using PanoramicData.NugetManagement.Rules;
using PanoramicData.NugetManagement.Services;
using PanoramicData.NugetManagement.Web.Remediations;

namespace PanoramicData.NugetManagement.Test;

/// <summary>
/// AI-05: the generated CLAUDE.md and AGENTS.md follow the wording standard the shared Skills
/// instructions set for all generated text: no em dashes, and a heading capitalises its first word only.
/// </summary>
public class InstructionFileWordingTests(ITestOutputHelper output) : TestWithOutput(output), IDisposable
{
	private const char _emDash = '—';

	private readonly string _root = Directory.CreateTempSubdirectory("wording").FullName;

	public void Dispose()
	{
		Directory.Delete(_root, recursive: true);
		GC.SuppressFinalize(this);
	}

	/// <summary>
	/// The AGENTS.md as generated by template v1.2, as it sits in the estate's repositories.
	/// </summary>
	private static string GeneratedV12Agents => Standards.AgentsMdContent
		.Replace("# Agent instructions", "# Agent Instructions")
		.Replace("read it before starting work, as it documents", $"read it before starting work {_emDash} it documents");

	[Fact]
	public void ShouldBeRegisteredForAi05()
		=> new RemediationRegistry().Get("AI-05").Should().NotBeNull();

	[Fact]
	public void TheCurrentTemplates_ShouldContainNoEmDash()
	{
		Standards.ClaudeMdContent.Should().NotContain(_emDash.ToString());
		Standards.AgentsMdContent.Should().NotContain(_emDash.ToString());
	}

	[Fact]
	public void TheCurrentTemplates_ShouldCapitaliseHeadingsFirstWordOnly()
	{
		Standards.AgentsMdContent.Should().Contain("# Agent instructions").And.NotContain("# Agent Instructions");
		Standards.ClaudeMdContent.Should().NotContain("# Claude Instructions");
	}

	[Fact]
	public async Task ShouldPass_ForTheCurrentTemplates()
	{
		var result = await EvaluateAsync(Standards.ClaudeMdContent, Standards.AgentsMdContent).ConfigureAwait(true);

		result.Passed.Should().BeTrue();
	}

	[Fact]
	public async Task ShouldBeNotApplicable_WithNeitherFile()
	{
		var result = await EvaluateAsync(null, null).ConfigureAwait(true);

		result.IsApplicable.Should().BeFalse();
	}

	[Fact]
	public async Task ShouldFail_ForTheGeneratedV12Agents()
	{
		var result = await EvaluateAsync(Standards.ClaudeMdContent, GeneratedV12Agents).ConfigureAwait(true);

		result.Passed.Should().BeFalse();
		result.Advisory!.Data["remediation_type"].Should().Be("replace_regex_in_files");
		result.Advisory.Data["globs"].Should().BeEquivalentTo(new[] { "AGENTS.md" });
		new RemediationRegistry().CanRemediate(result).Should().BeTrue();
	}

	[Fact]
	public async Task Fix_ShouldTurnTheGeneratedV12AgentsIntoTheCurrentTemplate()
	{
		// Fixing the estate's files must land exactly on what a new repository gets, or the fix and the
		// template drift apart.
		var fixedContent = await ApplyFixAsync(GeneratedV12Agents).ConfigureAwait(true);

		Normalise(fixedContent).Should().Be(Normalise(Standards.AgentsMdContent));
	}

	[Fact]
	public async Task Fix_ShouldPassTheRuleAfterwards()
	{
		var fixedContent = await ApplyFixAsync(GeneratedV12Agents).ConfigureAwait(true);

		var after = await EvaluateAsync(Standards.ClaudeMdContent, fixedContent).ConfigureAwait(true);
		after.Passed.Should().BeTrue();
	}

	[Fact]
	public async Task Fix_ShouldKeepWhatARepositoryAddedToItsOwnAgentsMd()
	{
		const string addition = "## Repository notes\n\nRun the device tests only on the lab machine.\n";
		var customised = Normalise(GeneratedV12Agents) + "\n\n" + addition;

		var fixedContent = await ApplyFixAsync(customised).ConfigureAwait(true);

		fixedContent.Should().Contain(addition.TrimEnd());
		fixedContent.Should().NotContain(_emDash.ToString());
	}

	[Fact]
	public async Task ShouldNotFlagAnEmDashAPersonWrote_ItCannotRewrite()
	{
		// Only the two phrasings the template used are rewritten. Flagging a sentence someone wrote
		// themselves would leave a Fix button that changes nothing.
		var handWritten = Standards.AgentsMdContent + $"\nNote {_emDash} this one is ours.\n";

		var result = await EvaluateAsync(Standards.ClaudeMdContent, handWritten).ConfigureAwait(true);

		result.Passed.Should().BeTrue();
	}

	private async Task<string> ApplyFixAsync(string agents)
	{
		var failing = await EvaluateAsync(Standards.ClaudeMdContent, agents).ConfigureAwait(true);
		failing.Passed.Should().BeFalse();

		var path = Path.Combine(_root, "AGENTS.md");
		File.WriteAllText(path, agents);

		var applied = new List<string>();
		new RemediationRegistry().Get("AI-05")!.Apply(_root, failing, applied, null);

		applied.Should().ContainSingle().Which.Should().EndWith("AGENTS.md");
		return File.ReadAllText(path);
	}

	private static string Normalise(string text) => text.Replace("\r\n", "\n").Trim();

	private static async Task<RuleResult> EvaluateAsync(string? claude, string? agents)
	{
		var files = new Dictionary<string, string>();
		if (claude is not null)
		{
			files["CLAUDE.md"] = claude;
		}

		if (agents is not null)
		{
			files["AGENTS.md"] = agents;
		}

		var context = new RepositoryContext
		{
			FullName = "panoramicdata/TeamViewer.Api",
			Name = "TeamViewer.Api",
			DefaultBranch = "main",
			Options = new RepoOptions(),
			FilePaths = [.. files.Keys],
			FileContents = files
		};

		return await RuleRegistry.Rules.Single(r => r.RuleId == "AI-05")
			.EvaluateAsync(context, CancellationToken.None)
			.ConfigureAwait(false);
	}
}
